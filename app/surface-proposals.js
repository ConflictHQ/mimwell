/* ── Proposal queue (W1.7) ────────────────────────────────────────────────────
 * What an organizer thinks should be true, awaiting curation. Reads
 * app/proposals.json (proposals/v1; written by aggregate-brains and, once the
 * W1.9 merger lands, by producers like navegador). Read-only by design: the
 * curator's act is copying an entry into the relevant fill-in
 * (app/equivalences.json for equivalence proposals). The page says exactly
 * that, per proposal, so acceptance is a deliberate, reviewable edit.
 */
(function (global) {
  'use strict';
  var esc = function (s) { return global.KBShell.esc(s); };
  var fetchJson = function (u, f) { return global.KBShell.fetchJson(u, f); };
  var ACCEPT_INTO = { equivalence: 'app/equivalences.json' };

  function confChip(c) {
    var pct = Math.round(Number(c || 0) * 100);
    return '<span class="ks-chip ' + (pct >= 90 ? 'ks-chip-ok' : pct >= 60 ? 'ks-chip-warn' : 'ks-chip-muted') + '">' + pct + '% confidence</span>';
  }

  function entry(p) {
    var into = ACCEPT_INTO[p.kind] || 'the matching fill-in';
    var simple = '<div class="kb-easy-only"><p>Someone suggested a connection. It has not been accepted.</p><p>' + esc(p.evidence || 'No source attached') + '</p><p>This queue is read-only. Ask a curator to accept or send it back using the owning brain’s writing workspace.</p><button type="button" data-kb-show-advanced>Show the exact suggestion</button></div>';
    return '<li class="ks-entry">' + simple + '<div data-kb-advanced>' +
      '<div class="ks-entry-head"><span class="ks-chip">' + esc(p.kind) + '</span><span class="ks-chip">' + esc(p.rel) + '</span>' +
        confChip(p.confidence) + '<span class="ks-chip ks-chip-muted">by ' + esc(p.proposed_by) + '</span></div>' +
      '<h3 class="ks-entry-title"><span class="ks-mono">' + esc(p.source) + '</span> → <span class="ks-mono">' + esc(p.target) + '</span></h3>' +
      '<p class="ks-entry-body">' + esc(p.evidence) + '</p>' +
      '<div class="ks-entry-foot"><span>to accept: copy this pair into <span class="ks-mono">' + esc(into) + '</span> with rel <span class="ks-mono">' + esc(p.rel) + '</span>; to reject: leave it</span></div>' +
    '</div></li>';
  }

  function mount(host) {
    global.KBShell.mount({ title: 'Proposals' }).then(function () {
      return fetchJson('/app/proposals.json', null);
    }).then(function (data) {
      var list = (data && data.proposals) || [];
      if (!data) {
        host.innerHTML = '<div class="ks-state"><div class="ks-state-title">No proposals file</div><div>Proposals are written by <span class="ks-mono">make aggregate-brain</span> when this brain federates children. A single brain has nothing to propose.</div></div>';
        return;
      }
      if (!list.length) {
        host.innerHTML = '<div class="ks-state"><div class="ks-state-title">Queue empty</div><div>Nothing awaiting curation.</div></div>';
        return;
      }
      var byKind = {};
      list.forEach(function (p) { (byKind[p.kind] = byKind[p.kind] || []).push(p); });
      host.innerHTML = Object.keys(byKind).sort().map(function (k) {
        return '<div class="ks-section">' + esc(k) + ' (' + byKind[k].length + ')</div><ul class="ks-list">' +
          byKind[k].map(entry).join('') + '</ul>';
      }).join('') + '<p class="ks-note">generated by ' + esc(data.generator || '?') + ' · ' + esc(data.format || '') + '</p>';
    });
  }

  function init() { var h = document.querySelector('[data-kb-surface="proposals"]'); if (h) mount(h); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
  global.KBProposals = { mount: mount, entry: entry };
})(window);
